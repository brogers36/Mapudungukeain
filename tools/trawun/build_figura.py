#!/usr/bin/env python3
"""Copy the game's avatar code (characters, Vestuario items, figureSVG) into trawun/figura.js, so Trawün draws a shared
Vestuario post from its outfit data (character + item ids) instead of accepting an image. Run after changing the
Vestuario in index.html:  python3 tools/trawun/build_figura.py index.html trawun/figura.js"""
import sys, re
src = open(sys.argv[1], encoding='utf-8').read()
a = src.index('const SKIN = {')
m = re.search(r'\nfunction figureSVG\(p,outfit\)\{.*?\n\}\n', src[a:], re.S)
assert m, 'figureSVG not found'
body = src[a:a + m.end()]
for need in ('const PEOPLE = [', 'const ITEMS = [', 'const SLOT_ORDER=', 'const fits=', 'function shd('):
    assert need in body, need + ' missing from the copied block'
esc = re.search(r'const esc = s => .*?\n', src).group(0)
out = ('/* Generated by tools/trawun/build_figura.py from the game (index.html). Do not edit by hand. */\n'
       '(function(){\n' + esc + body +
       'window.FIG={PEOPLE:PEOPLE,ITEMS:ITEMS,figureSVG:figureSVG,fits:fits};\n})();\n')
open(sys.argv[2], 'w', encoding='utf-8').write(out)
print('wrote', sys.argv[2], len(out), 'bytes')
